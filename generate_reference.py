#!/usr/bin/env python3
"""Generate api-reference.md from openapi.yaml.

Docs-as-code workflow: the OpenAPI spec is the single source of truth for
endpoints, parameters, schemas and examples. Run this script in CI to rebuild
the reference whenever the spec changes.

Usage: python3 generate_reference.py
Requires: PyYAML (pip install pyyaml)
"""
import json
import re
import yaml

SPEC = yaml.safe_load(open("openapi.yaml", encoding="utf-8"))
BASE = SPEC["servers"][0]["url"]


def resolve(node):
    """Follow a $ref pointer inside the spec."""
    while isinstance(node, dict) and "$ref" in node:
        target = SPEC
        for part in node["$ref"][2:].split("/"):
            target = target[part]
        node = target
    return node


def one_line(text):
    return re.sub(r"\s+", " ", (text or "").strip())


def permission(description):
    match = re.search(r"\*\*Required permission:\*\* `([^`]+)`", description or "")
    return match.group(1) if match else None


def body_without_permission(description):
    return re.sub(r"\n*\*\*Required permission:\*\* `[^`]+`\s*$", "", description.strip())


def schema_rows(schema):
    schema = resolve(schema)
    required = set(schema.get("required", []))
    rows = []
    for name, prop in schema.get("properties", {}).items():
        prop = resolve(prop)
        ptype = prop.get("type", "string")
        desc = one_line(prop.get("description"))
        if "enum" in prop:
            desc = (desc + " " if desc else "") + "Allowed values: " + ", ".join(f"`{v}`" for v in prop["enum"]) + "."
        rows.append((name, ptype, "Yes" if name in required else "No", desc))
    return rows


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out)


def curl_example(path, method, op):
    url = BASE + path.replace("{key_id}", "payments-prod")
    lines = [f"curl -X {method.upper()} {url} \\", '  -H "Authorization: Bearer $VAULTLINE_TOKEN"']
    body = op.get("requestBody")
    if body:
        example = body["content"]["application/json"].get("example")
        lines[-1] += " \\"
        lines.append('  -H "Content-Type: application/json" \\')
        lines.append(f"  -d '{json.dumps(example)}'")
    return "\n".join(lines)


out = []
info = SPEC["info"]
out.append(f"# {info['title']} reference\n")
out.append(f"**Version {info['version']}** | Base URL: `{BASE}`\n")
out.append("*Generated from `openapi.yaml`. Do not edit this file by hand.*\n")
out.append(info["description"].strip() + "\n")

out.append("## Authentication\n")
out.append(resolve(SPEC["components"]["securitySchemes"]["bearerAuth"])["description"].strip() + "\n")

out.append("## Operations\n")
ops = []
for path, methods in SPEC["paths"].items():
    for method, op in methods.items():
        ops.append((path, method, op))
out.append(table(
    ["Operation", "Method and path", "Permission"],
    [[f"[{op['summary']}](#{re.sub(r'[^a-z0-9]+', '-', op['summary'].lower()).strip('-')})",
      f"`{m.upper()} /v2{p}`", f"`{permission(op['description'])}`"] for p, m, op in ops],
) + "\n")

current_tag = None
for tag in SPEC["tags"]:
    out.append(f"## {tag['name']}\n")
    out.append(tag["description"] + "\n")
    for path, method, op in ops:
        if op["tags"][0] != tag["name"]:
            continue
        out.append(f"### {op['summary']}\n")
        out.append(f"`{method.upper()} /v2{path}`\n")
        out.append(body_without_permission(op["description"]) + "\n")
        out.append(f"**Required permission:** `{permission(op['description'])}`\n")

        params = [resolve(p) for p in op.get("parameters", [])]
        rows = [[f"`{p['name']}`", f"{p['schema']['type']} ({p['in']})",
                 "Yes" if p.get("required") else "No", one_line(p.get("description"))] for p in params]
        if op.get("requestBody"):
            schema = op["requestBody"]["content"]["application/json"]["schema"]
            rows += [[f"`{n}`", f"{t} (body)", r, d] for n, t, r, d in schema_rows(schema)]
        out.append("**Parameters**\n")
        out.append(table(["Parameter", "Type", "Required", "Description"], rows) + "\n")

        out.append("**Example request**\n")
        out.append("```bash\n" + curl_example(path, method, op) + "\n```\n")

        success = next(code for code in op["responses"] if code.startswith("2"))
        resp = resolve(op["responses"][success])
        out.append(f"**Response: {success}**\n")
        out.append(one_line(resp["description"]) + "\n")
        out.append("```json\n" + json.dumps(resp["content"]["application/json"]["example"], indent=2) + "\n```\n")

        errors = [(c, resolve(r)) for c, r in op["responses"].items() if not c.startswith("2")]
        out.append("**Errors**\n")
        err_rows = []
        for code, r in errors:
            err_code = r["content"]["application/json"]["example"]["error"]
            err_rows.append([code, f"`{err_code}`", one_line(r["description"])])
        out.append(table(["HTTP status", "Error code", "Meaning and action"], err_rows) + "\n")

out.append("## Error format\n")
out.append("Every error response uses the same JSON structure.\n")
out.append(table(["Field", "Type", "Required", "Description"],
                 [[f"`{n}`", t, r, d] for n, t, r, d in schema_rows(SPEC["components"]["schemas"]["Error"])]) + "\n")
example = SPEC["components"]["responses"]["NotFound"]["content"]["application/json"]["example"]
out.append("```json\n" + json.dumps(example, indent=2) + "\n```\n")

open("api-reference.md", "w", encoding="utf-8").write("\n".join(out))
print("Wrote api-reference.md")
